import esbuild from "esbuild";
import process from "process";
import { builtinModules as builtins } from "module";
import fs from "fs";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

// Node 内置模块 stub（2026-10-22 上架整改）：
// rss-parser 的 lib/parser.js 顶层 require("http")/require("https")/require("url")
// （只服务其 parseURL 路径，本插件只走 requestUrl + parseString）。
// 若保留为 external require，移动端 Obsidian（无 Node 模块）加载插件即崩，
// 与 manifest isDesktopOnly:false 直接矛盾——故把这三个模块 stub 成空对象。
// 其余 builtin 仍走 external（源码不 import Node 模块，此处仅保险）。
const nodeStubPlugin = {
  name: "node-builtin-stub",
  setup(build) {
    build.onResolve({ filter: /^(http|https|url)$/ }, (args) => ({
      path: args.path,
      namespace: "node-builtin-stub",
    }));
    build.onLoad({ filter: /.*/, namespace: "node-builtin-stub" }, () => ({
      contents: "module.exports = {};",
      loader: "js",
    }));
  },
};

// 部署到 obsidian 库插件目录；目标可用 RSS_VAULT 环境变量覆盖（默认 E:\Obsidian\vault002-outup-others）。
// 只拷贝构建产物，绝不覆盖 data.json / vault 根 .env。
// 注意：目录名 = 插件 ID（2026-10-22 obsidian-rss-reader → rss-reader；
// 2026-10-23 rss-reader → markdown-rss：该 ID 被已下架插件占用，目录站禁用复用）。
const deploy = () => {
  const rssVault = process.env.RSS_VAULT || "E:\\Obsidian\\vault002-outup-others";
  const pluginDir = path.join(rssVault, ".obsidian", "plugins", "markdown-rss");
  try {
    fs.mkdirSync(pluginDir, { recursive: true });
    const artifacts = ["main.js", "manifest.json", "styles.css"];
    for (const f of artifacts) {
      if (fs.existsSync(f)) {
        fs.copyFileSync(f, path.join(pluginDir, f));
        console.log(`[deploy] ${f} -> ${pluginDir}`);
      }
    }
    console.log(`[deploy] synced to ${pluginDir}`);
  } catch (e) {
    console.error(`[deploy] failed: ${e.message}`);
  }
};

const buildOptions = {
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "ES6",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  plugins: [nodeStubPlugin],
  loader: {
    ".md": "text",
  },
};

if (prod) {
  esbuild
    .build(buildOptions)
    .then(() => deploy())
    .catch(() => process.exit(1));
} else {
  esbuild
    .context(buildOptions)
    .then(async (context) => {
      context.onEnd(() => deploy());
      await context.watch();
      deploy(); // 首次立即同步一次
      console.log("Watching for changes...");
    })
    .catch(() => process.exit(1));
}
